from typing import Protocol
from aero_ai_studio.observation.models import Observation


class GazeboSensorProvider(Protocol):
    """Camera/Depth/LiDAR/IMU/GPS/Range implementations must carry sample timestamps."""
    def start(self) -> None: ...
    def stop(self) -> None: ...
    def get_latest_observation(self) -> Observation | None: ...
    def get_sensor_status(self) -> dict: ...
